"""Rebuild textbook text extracts from verified ChinaTextbook PDFs.

The registered extracts are byte-pinned by `extractedSha256` in
`resources/curriculum/chinatextbook-{chinese,primary}-v1.json`. This reruns the
same extraction as the original importers (PyMuPDF `page.get_text('text')`,
identical JSON serialization) into a separate asset root and accepts a file
only when both the source PDF and the regenerated bytes match the manifest.
Nothing in Git is rewritten. PyMuPDF 1.26.6 reproduced the registered hashes;
other MuPDF releases may extract slightly different text and are reported as
mismatches instead of being installed.

Usage:
  python -X utf8 scripts/operations/restore-textbook-extracts.py \
    --textbook-root /data/studyagent/ChinaTextbook --asset-root /data/studyagent/assets
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import sys

import fitz

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts/assets'))
MANIFESTS = {
    'chinese': ROOT / 'resources/curriculum/chinatextbook-chinese-v1.json',
    'primary': ROOT / 'resources/curriculum/chinatextbook-primary-v1.json',
}
PREFIX = 'data/assets/'


def sha256_file(path: Path) -> str:
    value = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b''):
            value.update(chunk)
    return value.hexdigest()


def target_of(asset_root: Path, extracted_path: str) -> Path:
    if not extracted_path.startswith(PREFIX):
        raise ValueError('Unexpected extracted path: ' + extracted_path)
    relative = PurePosixPath(extracted_path[len(PREFIX):])
    if relative.is_absolute() or '..' in relative.parts:
        raise ValueError('Unsafe extracted path: ' + extracted_path)
    return asset_root.joinpath(*relative.parts)


def pages_of(original: Path) -> list[dict]:
    document = fitz.open(original)
    try:
        if document.needs_pass or not document.is_pdf:
            raise ValueError('Unusable PDF: ' + str(original))
        return [{'page': index + 1, 'text': page.get_text('text')} for index, page in enumerate(document)]
    finally:
        document.close()


def chinese_body(book: dict, original: Path) -> bytes:
    normalization = book.get('textNormalization')
    if normalization:
        # Tone-decoded derivative of the verified pinyin edition; derived from the legacy extract.
        from textbook_pinyin_decoding import extract_verified
        legacy = {'format': 'chinatextbook-extraction-v1', 'id': book['id'], 'sourceSha256': book['sha256'], 'pages': pages_of(original)}
        legacy_body = json.dumps(legacy, ensure_ascii=False, indent=2).encode('utf-8')
        if hashlib.sha256(legacy_body).hexdigest() != normalization.get('legacyExtractedSha256'):
            raise ValueError('legacy extraction differs')
        legacy_path = Path(os.environ.get('TMPDIR', '/tmp')) / ('legacy-' + book['sha256'][:16] + '.json')
        legacy_path.write_bytes(legacy_body)
        try:
            normalized, _ = extract_verified(original, legacy_path)
        finally:
            legacy_path.unlink(missing_ok=True)
        return normalized
    extracted = {'format': 'chinatextbook-extraction-v1', 'id': book['id'], 'sourceSha256': book['sha256'], 'pages': pages_of(original)}
    return json.dumps(extracted, ensure_ascii=False, indent=2).encode('utf-8')


def primary_body(book: dict, original: Path) -> bytes:
    source_relative = book['sourceRelative'].split('/', 1)[1]
    extracted = {'format': 'chinatextbook-primary-extraction-v1', 'subject': book['subject'],
                 'sourceRelative': source_relative, 'sourceSha256': book['sha256'], 'pages': pages_of(original)}
    return json.dumps(extracted, ensure_ascii=False, separators=(',', ':')).encode('utf-8')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--textbook-root', type=Path, required=True)
    parser.add_argument('--asset-root', type=Path, required=True)
    args = parser.parse_args()
    counts = {'restored': 0, 'kept': 0, 'source_missing': 0, 'source_mismatch': 0, 'extract_mismatch': 0}
    failures: list[str] = []
    for collection, manifest in MANIFESTS.items():
        books = json.loads(manifest.read_text('utf-8'))['books']
        for book in books:
            target = target_of(args.asset_root, book['extractedPath'])
            if target.exists() and sha256_file(target) == book['extractedSha256']:
                counts['kept'] += 1
                continue
            original = args.textbook_root.joinpath(*PurePosixPath(book['repositoryPath']).parts)
            if not original.is_file():
                counts['source_missing'] += 1; failures.append('missing ' + book['repositoryPath']); continue
            if sha256_file(original) != book['sha256']:
                counts['source_mismatch'] += 1; failures.append('source ' + book['repositoryPath']); continue
            try:
                body = chinese_body(book, original) if collection == 'chinese' else primary_body(book, original)
            except ValueError as error:
                counts['extract_mismatch'] += 1; failures.append(f'extract {book["repositoryPath"]}: {error}'); continue
            if hashlib.sha256(body).hexdigest() != book['extractedSha256']:
                counts['extract_mismatch'] += 1; failures.append('extract ' + book['repositoryPath']); continue
            target.parent.mkdir(parents=True, exist_ok=True)
            partial = target.with_name(target.name + '.part')
            partial.write_bytes(body)
            os.replace(partial, target)
            counts['restored'] += 1
    print(json.dumps({'pymupdf': fitz.VersionBind, **counts}, ensure_ascii=False))
    for line in failures[:50]:
        print('FAILED', line)
    return 1 if failures else 0


if __name__ == '__main__':
    raise SystemExit(main())
